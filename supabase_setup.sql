-- 1. Table para sa Leaderboard Scores
CREATE TABLE IF NOT EXISTS scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  name TEXT NOT NULL,
  score INT NOT NULL,
  character_id INT NOT NULL
);

-- 2. Table para sa Dynamic Characters
CREATE TABLE IF NOT EXISTS characters (
  id INT PRIMARY KEY,
  name TEXT NOT NULL,
  image TEXT NOT NULL,
  is_custom BOOLEAN DEFAULT false
);

-- 3. I-enable ang Row Level Security (RLS)
ALTER TABLE scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE characters ENABLE ROW LEVEL SECURITY;

-- 4. Mga Security Policies (Para makapaglaro at makapag-save ang kahit sino)
DROP POLICY IF EXISTS "Public read scores" ON scores;
CREATE POLICY "Public read scores" ON scores FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public insert scores" ON scores;
CREATE POLICY "Public insert scores" ON scores FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public read characters" ON characters;
CREATE POLICY "Public read characters" ON characters FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public update characters" ON characters;
CREATE POLICY "Public update characters" ON characters FOR ALL USING (true) WITH CHECK (true);
